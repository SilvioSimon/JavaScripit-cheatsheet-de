// indexOf() gibt den Index des gesuchten Elements zurück.
// Existiert das Element nicht im Array, wird -1 zurückgegeben.

let numbers = [10, 20, 30, 40];

console.log(numbers.indexOf(30)); // 2 (30 befindet sich an Index 2)
console.log(numbers.indexOf(90)); // -1 (90 ist nicht im Array vorhanden)

